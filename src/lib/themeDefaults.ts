/** Merge partial/legacy scheme with defaults */
export function mergeScheme(partial: Partial<ColorScheme> | undefined, defaults: ColorScheme): ColorScheme {
  if (!partial) return { ...defaults };
  return { ...defaults, ...partial };
}
